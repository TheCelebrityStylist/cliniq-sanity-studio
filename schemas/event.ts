import { defineField, defineType } from 'sanity'

export default defineType({
  name: 'event',
  title: 'Events / Agenda',
  type: 'document',
  fields: [
    defineField({ name: 'title', title: 'Event Title / DJ Name', type: 'string', validation: (Rule) => Rule.required() }),
    defineField({ name: 'slug', title: 'Slug', type: 'slug', options: { source: 'title' }, validation: (Rule) => Rule.required() }),
    defineField({ name: 'date', title: 'Date', type: 'date', validation: (Rule) => Rule.required() }),
    defineField({ name: 'dj', title: 'DJ (links to the DJ page /dj/[slug] and shows as a "met {DJ}" line)', type: 'reference', to: [{ type: 'dj' }] }),
    defineField({ name: 'customTitleNl', title: 'Custom title NL (overrides the event name on the NL card/page)', type: 'string' }),
    defineField({ name: 'customTitleEn', title: 'Custom title EN (overrides the event name on the EN card/page)', type: 'string' }),
    defineField({ name: 'eventType', title: 'Event Type', type: 'string', initialValue: 'regular', options: { list: [
      { title: 'Regular Club Night', value: 'regular' },
      { title: 'Featured Event', value: 'featured' },
      { title: 'Special Event', value: 'special' },
      { title: 'Private Event', value: 'private' },
    ] } }),
    defineField({ name: 'openingTime', title: 'Opening Time', type: 'string', initialValue: '22:00' }),
    defineField({ name: 'closingTime', title: 'Closing Time', type: 'string', initialValue: '03:00' }),
    defineField({ name: 'minimumAge', title: 'Minimum Age', type: 'string', initialValue: '21+' }),
    defineField({ name: 'published', title: 'Published', type: 'boolean', initialValue: true }),
    defineField({ name: 'featured', title: 'Featured (show in the Featured Events section with its own flyer + page)', type: 'boolean', initialValue: false }),
    defineField({ name: 'showDetailPage', title: 'Special event — give this night its own event page (instead of linking to the DJ page)', type: 'boolean', initialValue: false }),
    defineField({ name: 'eventImage', title: 'Event Image Override', type: 'image', options: { hotspot: true } }),
    defineField({ name: 'flyerImage', title: 'Promo flyer (portrait — used for featured/special events)', type: 'image', options: { hotspot: true } }),
    defineField({ name: 'descriptionNl', title: 'Description NL', type: 'text', rows: 4 }),
    defineField({ name: 'descriptionEn', title: 'Description EN', type: 'text', rows: 4 }),
    defineField({ name: 'promoNl', title: 'Promo copy NL (full event-page body — shown on featured/special event pages)', type: 'text', rows: 6 }),
    defineField({ name: 'promoEn', title: 'Promo copy EN (full event-page body)', type: 'text', rows: 6 }),
    defineField({ name: 'metaTitleNl', title: 'SEO title NL (browser tab / Google result)', type: 'string' }),
    defineField({ name: 'metaTitleEn', title: 'SEO title EN', type: 'string' }),
    defineField({ name: 'metaDescriptionNl', title: 'SEO description NL (Google snippet)', type: 'text', rows: 3 }),
    defineField({ name: 'metaDescriptionEn', title: 'SEO description EN', type: 'text', rows: 3 }),
    defineField({ name: 'ticketUrl', title: 'Ticket / Reservation URL', type: 'url' }),
    defineField({ name: 'album', title: 'Related Album', type: 'reference', to: [{ type: 'album' }] }),
  ],
  preview: {
    select: { title: 'title', date: 'date', media: 'eventImage' },
    prepare({ title, date, media }) { return { title, subtitle: date, media } },
  },
})
